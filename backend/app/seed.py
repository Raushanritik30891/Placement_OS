def seed() -> None:
    Base.metadata.create_all(bind=engine)
    with SessionLocal() as db:
        topic_map = {}
        for name, slug, description in TOPICS:
            topic = db.scalar(select(Topic).where(Topic.slug == slug))
            if topic is None:
                topic = Topic(name=name, slug=slug, description=description)
                db.add(topic)
                db.flush()
            topic_map[slug] = topic.id

        for item in PROBLEMS:
            if db.scalar(select(Problem).where(Problem.slug == item["slug"])):
                continue
            data = dict(item)
            cases = data.pop("cases")
            configured_samples = data.get("samples", [])
            visible_cases = [(stdin, expected) for stdin, expected, is_hidden in cases if not is_hidden]
            if len(configured_samples) < 2:
                data["samples"] = [
                    {
                        "input": stdin,
                        "output": expected,
                        "explanation": configured_samples[0].get("explanation", "") if index == 0 and configured_samples else "",
                    }
                    for index, (stdin, expected) in enumerate(visible_cases[:2])
                ]
            data["topic_id"] = topic_map[data.pop("topic")]
            problem = Problem(**data, is_published=True)
            db.add(problem)
            db.flush()
            for stdin, expected, is_hidden in cases:
                db.add(ProblemTestCase(
                    problem_id=problem.id,
                    stdin=stdin,
                    expected_output=expected,
                    is_sample=not is_hidden,
                ))

        for category, topic, prompt, options, correct, explanation, difficulty in QUIZZES:
            existing = db.scalar(select(QuizQuestion).where(
                QuizQuestion.category == category,
                QuizQuestion.prompt == prompt,
            ))
            if existing is None:
                db.add(QuizQuestion(
                    category=category,
                    topic=topic,
                    prompt=prompt,
                    options=options,
                    correct_index=correct,
                    explanation=explanation,
                    difficulty=difficulty,
                ))
        db.commit()


if __name__ == "__main__":
    seed()
